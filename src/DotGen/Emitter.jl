# Emitter.jl: DotConfig → SystemVerilog.
#
# Datapath (one result per cycle):
#
#   per lane:  decode a_i, b_i → sign, significand, shift, special flags
#              product significand  (a multiplier, or a select/negate for ternary)
#              align onto the block's fixed-point grid  (exact, or window-truncated
#              against the block-max exponent)  → one signed term
#   block:     ONE reduction of all K terms  (3:2 carry-save tree + one CPA, or adder tree)
#              ONE normalize (leading-zero count + shift) and ONE rounding to the output
#
# Every width comes from `widths(cfg)`, the same numbers the reference model uses.

export emit_dot, emit_dot_string

const SV_BANNER = "// Generated by HWExplore DotGen. Do not edit; regenerate with `bin/hwx dot`."

slit(v::Integer) = v < 0 ? "-16'sd$(-v)" : "16'sd$v"
hexlit(w::Int, v::Integer) = "$(w)'h$(string(v, base=16))"
zext(sig::String, from::Int, to::Int) =
    to == from ? sig : to > from ? "{$(to - from)'b0, $sig}" : "$sig[$(to-1):0]"

"""
    lane_decode(io, f, p, W, idx) -> nothing

Emit the per-lane decoder for operand `p` ("a"/"b"): `p_c` (raw code), `p_s` (sign),
`p_sig`, `p_sh`, `p_nan`, `p_inf`, `p_zero`.
"""
function lane_decode(io, f::FPElem, p, H, HW)
    E, M, W = f.ebits, f.mbits, nbits(f)
    println(io, "    logic         $(p)_s, $(p)_nan, $(p)_inf, $(p)_zero;")
    println(io, "    logic [$(E-1):0]   $(p)_e;")
    println(io, "    logic [$(M-1):0]   $(p)_m;")
    println(io, "    logic [$(M):0]   $(p)_sig;")
    println(io, "    logic [$(E-1):0]   $(p)_em1;")
    println(io, "    logic [$(HW-1):0]   $(p)_sh;")
    println(io, "    assign $(p)_s   = $(p)_c[$(W-1)];")
    println(io, "    assign $(p)_e   = $(p)_c[$(M+E-1):$(M)];")
    println(io, "    assign $(p)_m   = $(p)_c[$(M-1):0];")
    nan = f.specials == :ieee ? "(&$(p)_e) & (|$(p)_m)" :
          f.specials == :e4m3 ? "(&$(p)_e) & (&$(p)_m)" : "1'b0"
    inf = f.specials == :ieee ? "(&$(p)_e) & ~(|$(p)_m)" : "1'b0"
    println(io, "    assign $(p)_nan = $nan;")
    println(io, "    assign $(p)_inf = $inf;")
    special = f.specials == :none ? "" : "($(p)_nan | $(p)_inf) ? '0 : "
    println(io, "    assign $(p)_sig = $(special){|$(p)_e, $(p)_m};      // implicit bit = (e != 0)")
    println(io, "    assign $(p)_em1 = $(p)_e - $(E)'d1;")
    println(io, "    assign $(p)_sh  = ($(p)_e == '0$(f.specials == :none ? "" : " || $(p)_nan || $(p)_inf")) ? '0 : $(p)_em1[$(HW-1):0];")
    println(io, "    assign $(p)_zero = ~$(p)_nan & ~$(p)_inf & ($(p)_sig == '0);")
end

function lane_decode(io, f::IntElem, p, H, HW)
    B = f.bits
    println(io, "    logic         $(p)_s, $(p)_nan, $(p)_inf, $(p)_zero;")
    println(io, "    logic [$(B-1):0]   $(p)_sig;")
    println(io, "    logic [0:0]   $(p)_sh;")
    println(io, "    assign $(p)_s    = $(p)_c[$(B-1)];")
    println(io, "    assign $(p)_sig  = $(p)_s ? -$(p)_c : $(p)_c;   // |x|; -2^(B-1) stays 2^(B-1) unsigned")
    println(io, "    assign $(p)_sh   = 1'b0;")
    println(io, "    assign $(p)_nan  = 1'b0;")
    println(io, "    assign $(p)_inf  = 1'b0;")
    println(io, "    assign $(p)_zero = ($(p)_c == '0);")
end

function lane_decode(io, ::TernaryElem, p, H, HW)
    println(io, "    logic         $(p)_s, $(p)_nan, $(p)_inf, $(p)_zero;")
    println(io, "    logic [0:0]   $(p)_sig, $(p)_sh;")
    println(io, "    assign $(p)_s    = $(p)_c[1];")
    println(io, "    assign $(p)_sig  = $(p)_c[0];      // 01 → +1, 11 → -1, 00/10 → 0")
    println(io, "    assign $(p)_sh   = 1'b0;")
    println(io, "    assign $(p)_nan  = 1'b0;")
    println(io, "    assign $(p)_inf  = 1'b0;")
    println(io, "    assign $(p)_zero = ~$(p)_c[0];")
end

# Integer × integer: a signed multiply (or a select/negate for ternary) is the term directly.
function lane_int_term(io, c::DotConfig, w)
    Ws = w.Ws
    sext(x, from) = Ws == from ? x : "{{$(Ws - from){$x[$(from-1)]}}, $x}"
    a, b = c.a, c.b
    if a isa TernaryElem && b isa TernaryElem
        println(io, "    assign term = (a_c[0] & b_c[0]) ? ((a_c[1] ^ b_c[1]) ? '1 : $(Ws)'d1) : '0;")
    elseif a isa TernaryElem || b isa TernaryElem
        t, x, B = a isa TernaryElem ? ("a", "b", nbits(b)) : ("b", "a", nbits(a))
        println(io, "    // ternary operand: no multiplier, just select / negate")
        println(io, "    logic [$(Ws-1):0] xs;")
        println(io, "    assign xs   = $(sext("$(x)_c", B));")
        println(io, "    assign term = $(t)_c[0] ? ($(t)_c[1] ? -xs : xs) : '0;")
    else
        Bp = nbits(a) + nbits(b)
        println(io, "    logic signed [$(Bp-1):0] prod;")
        println(io, "    assign prod = \$signed(a_c) * \$signed(b_c);")
        println(io, "    assign term = $(sext("prod", Bp));")
    end
end

# Product significand of the sign-magnitude path; a ternary operand turns the multiplier into a select.
function product_expr(c::DotConfig, w)
    Sp = w.Sp
    if c.a isa TernaryElem && c.b isa TernaryElem
        return "{$(Sp-1)'b0, a_sig & b_sig}"
    elseif c.a isa TernaryElem
        return "a_sig ? $(zext("b_sig", w.Sb, Sp)) : '0   /* ternary: no multiplier */"
    elseif c.b isa TernaryElem
        return "b_sig ? $(zext("a_sig", w.Sa, Sp)) : '0   /* ternary: no multiplier */"
    end
    return "$(zext("a_sig", w.Sa, Sp)) * $(zext("b_sig", w.Sb, Sp))"
end

# Emit a balanced max-tree over `names` (all `width` bits wide); returns the root signal name.
function emit_max_tree(io, names::Vector{String}, width::Int)
    level = 0
    while length(names) > 1
        nxt = String[]
        for j in 1:2:length(names)
            if j == length(names)
                push!(nxt, names[j])
            else
                nm = "emax_l$(level)_$(length(nxt))"
                println(io, "  logic [$(width-1):0] $nm;")
                println(io, "  assign $nm = ($(names[j]) > $(names[j+1])) ? $(names[j]) : $(names[j+1]);")
                push!(nxt, nm)
            end
        end
        names = nxt; level += 1
    end
    return names[1]
end

# Emit the reduction of `terms` (Ws-bit two's complement); returns the sum signal name.
function emit_tree(io, terms::Vector{String}, Ws::Int, kind::Symbol)
    length(terms) == 1 && return terms[1]
    if kind == :adder
        level = 0
        while length(terms) > 1
            nxt = String[]
            for j in 1:2:length(terms)
                if j == length(terms)
                    push!(nxt, terms[j])
                else
                    nm = "add_l$(level)_$(length(nxt))"
                    println(io, "  logic [$(Ws-1):0] $nm;")
                    println(io, "  assign $nm = $(terms[j]) + $(terms[j+1]);")
                    push!(nxt, nm)
                end
            end
            terms = nxt; level += 1
        end
        return terms[1]
    end
    # Word-level Wallace tree of 3:2 compressors (full adders on every bit), then one CPA.
    level = 0; n = 0
    while length(terms) > 2
        nxt = String[]
        j = 1
        while j + 2 <= length(terms)
            x, y, z = terms[j], terms[j+1], terms[j+2]
            s, cy, mj = "csa$(n)_s", "csa$(n)_c", "csa$(n)_maj"
            println(io, "  logic [$(Ws-1):0] $s, $cy, $mj;   // level $level")
            println(io, "  assign $s  = $x ^ $y ^ $z;")
            println(io, "  assign $mj = ($x & $y) | ($x & $z) | ($y & $z);")
            println(io, "  assign $cy = {$mj[$(Ws-2):0], 1'b0};")
            push!(nxt, s, cy)
            n += 1; j += 3
        end
        append!(nxt, terms[j:end])
        terms = nxt; level += 1
    end
    println(io, "  logic [$(Ws-1):0] tree_sum;")
    println(io, "  assign tree_sum = $(terms[1]) + $(terms[2]);   // the only carry-propagate adder")
    return "tree_sum"
end

# A pipeline boundary: registered when `reg`, a plain wire otherwise.
function emit_boundary(io, reg::Bool, sigs::Vector{Tuple{String,String,String}})
    # sigs: (decl_suffix, dst, src), e.g. ("logic [27:0]", "sum_q", "sum_d")
    for (decl, dst, _) in sigs
        println(io, "  $decl $dst;")
    end
    if reg
        println(io, "  always_ff @(posedge clk_i or negedge rst_ni) begin")
        println(io, "    if (!rst_ni) begin")
        for (_, dst, _) in sigs
            println(io, "      $dst <= '0;")
        end
        println(io, "    end else begin")
        for (_, dst, src) in sigs
            println(io, "      $dst <= $src;")
        end
        println(io, "    end")
        println(io, "  end")
    else
        for (_, dst, src) in sigs
            println(io, "  assign $dst = $src;")
        end
    end
end

"""
    emit_dot_string(cfg) -> String

SystemVerilog for the dot-product engine described by `cfg`.
"""
function emit_dot_string(c::DotConfig)
    w = widths(c)
    K, Ws, Wn = c.block, w.Ws, w.Wn
    WA, WB, WO = nbits(c.a), nbits(c.b), nbits(c.out)
    int_path = is_int_only(c)
    specials = has_specials(c.a) || has_specials(c.b)
    fpout = c.out isa FPOut
    reg_terms, reg_sum, reg_out = c.stages >= 3, c.stages >= 2, c.stages >= 1

    io = IOBuffer()
    println(io, SV_BANNER)
    println(io, "//")
    for l in split(describe(c), '\n')
        println(io, "// ", l)
    end
    println(io, "//")
    println(io, "// Lane i occupies a_i[$(WA)*i +: $(WA)] and b_i[$(WB)*i +: $(WB)].",
            c.scale_a || c.scale_b ? " Scales are E8M0 (0xFF = NaN)." : "")
    if fpout
        println(io, "// Exact zero → +0. NaN out = $(hexlit(WO, canonical_nan(c.out))). ",
                "Overflow → $(c.rounding == :rne ? "±Inf" : "±max finite").")
    end
    println(io)
    println(io, "/* verilator lint_off UNUSEDSIGNAL */   // top carry/implicit bits are unused by construction")
    println(io, "module $(c.name) (")
    println(io, "  input  logic              clk_i,")
    println(io, "  input  logic              rst_ni,")
    println(io, "  input  logic              valid_i,")
    println(io, "  input  logic [$(K*WA-1):0] a_i,")
    println(io, "  input  logic [$(K*WB-1):0] b_i,")
    c.scale_a && println(io, "  input  logic [7:0]        xa_i,")
    c.scale_b && println(io, "  input  logic [7:0]        xb_i,")
    println(io, "  output logic              valid_o,")
    println(io, "  output logic [$(WO-1):0]       result_o")
    println(io, ");")
    println(io)

    # ---------------- per-lane: decode, multiply, align ----------------
    println(io, "  // ---------------- per lane: decode → product → align ----------------")
    println(io, "  logic [$(K*Ws-1):0] terms_d;")
    window = c.window !== nothing
    window && println(io, "  logic [$(K*w.HpW-1):0] psh_all;")
    specials && println(io, "  logic [$(K-1):0] l_nan, l_pinf, l_ninf;")
    int_path || println(io, "  logic [$(K-1):0] negs;   // lanes whose term is one's-complemented")
    if window
        println(io, "  logic [$(w.HpW-1):0] emax;   // largest product exponent in the block")
    end
    println(io)
    println(io, "  for (genvar i = 0; i < $K; i++) begin : g_lane")
    println(io, "    logic [$(WA-1):0] a_c;")
    println(io, "    logic [$(WB-1):0] b_c;")
    println(io, "    logic [$(Ws-1):0] term;")
    println(io, "    assign a_c = a_i[$(WA)*i +: $(WA)];")
    println(io, "    assign b_c = b_i[$(WB)*i +: $(WB)];")
    if int_path
        lane_int_term(io, c, w)
    else
        lane_decode(io, c.a, "a", w.Ha, w.HaW)
        lane_decode(io, c.b, "b", w.Hb, w.HbW)
        println(io, "    logic [$(w.Sp-1):0] psig;")
        println(io, "    logic [$(w.HpW-1):0] psh;")
        println(io, "    logic [$(w.Mw-1):0] pmag;")
        println(io, "    logic         neg;")
        println(io, "    assign psig = $(product_expr(c, w));")
        println(io, "    assign psh  = (psig == '0) ? '0 : $(zext("a_sh", w.HaW, w.HpW)) + $(zext("b_sh", w.HbW, w.HpW));   // zero products never set the block max")
        println(io, "    assign neg  = a_s ^ b_s;")
        if window
            pad = c.window - w.Sp
            top = pad == 0 ? "psig" : "{psig, $(pad)'b0}"
            println(io, "    assign pmag = $top >> (emax - psh);   // align to block max, truncate")
        else
            println(io, "    assign pmag = $(zext("psig", w.Sp, w.Mw)) << psh;      // exact: no bits dropped")
        end
        # One's complement here; the +1 of every negative lane is added once, as a popcount operand
        # of the reduction tree, instead of a Ws-bit incrementer per lane.
        println(io, "    assign term = neg ? ~$(zext("pmag", w.Mw, Ws)) : $(zext("pmag", w.Mw, Ws));   // -x = ~x + 1")
        println(io, "    assign negs[i] = neg;")
        window && println(io, "    assign psh_all[$(w.HpW)*i +: $(w.HpW)] = psh;")
        if specials
            println(io, "    assign l_nan[i]  = a_nan | b_nan | (a_inf & b_zero) | (b_inf & a_zero);")
            println(io, "    assign l_pinf[i] = (a_inf | b_inf) & ~l_nan[i] & ~neg;")
            println(io, "    assign l_ninf[i] = (a_inf | b_inf) & ~l_nan[i] &  neg;")
        end
    end
    println(io, "    assign terms_d[$(Ws)*i +: $(Ws)] = term;")
    println(io, "  end")
    println(io)

    if !int_path
        CW = bitlen(K)
        println(io, "  // Σ(+1) for the one's-complemented lanes: one small operand instead of $K incrementers")
        println(io, "  logic [$(CW-1):0] negcnt;")
        println(io, "  always_comb begin")
        println(io, "    negcnt = '0;")
        println(io, "    for (int k = 0; k < $K; k++) negcnt = negcnt + $(CW)'(negs[k]);")
        println(io, "  end")
        println(io, "  logic [$(Ws-1):0] negfix;")
        println(io, "  assign negfix = $(zext("negcnt", CW, Ws));")
        println(io)
    end
    if window
        root = emit_max_tree(io, ["psh_all[$(w.HpW*i) +: $(w.HpW)]" for i in 0:K-1], w.HpW)
        println(io, "  assign emax = $root;")
        println(io)
    end

    # block-level specials and the exponent of the sum's LSB
    bound1 = Tuple{String,String,String}[("logic [$(K*Ws-1):0]", "terms_q", "terms_d")]
    int_path || push!(bound1, ("logic [$(Ws-1):0]", "negfix_q", "negfix"))
    if fpout
        nan_terms = String[]
        specials && push!(nan_terms, "(|l_nan)", "((|l_pinf) & (|l_ninf))")
        c.scale_a && push!(nan_terms, "(xa_i == 8'hFF)")
        c.scale_b && push!(nan_terms, "(xb_i == 8'hFF)")
        println(io, "  logic nan_d, pinf_d, ninf_d;")
        println(io, "  assign nan_d  = $(isempty(nan_terms) ? "1'b0" : join(nan_terms, " | "));")
        println(io, "  assign pinf_d = $(specials ? "|l_pinf" : "1'b0");")
        println(io, "  assign ninf_d = $(specials ? "|l_ninf" : "1'b0");")
        C = w.lsb - 127 * (c.scale_a + c.scale_b) + (window ? w.Sp - c.window : 0)
        parts = [slit(C)]
        c.scale_a && push!(parts, "\$signed({8'b0, xa_i})")
        c.scale_b && push!(parts, "\$signed({8'b0, xb_i})")
        window && push!(parts, "\$signed({$(16 - w.HpW)'b0, emax})")
        println(io, "  logic signed [15:0] e_lsb_d;   // the sum's LSB has weight 2^e_lsb")
        println(io, "  assign e_lsb_d = $(join(parts, " + "));")
        append!(bound1, [("logic", "nan_q1", "nan_d"), ("logic", "pinf_q1", "pinf_d"),
                         ("logic", "ninf_q1", "ninf_d"), ("logic signed [15:0]", "e_lsb_q1", "e_lsb_d")])
    end
    println(io)
    println(io, "  // ---------------- stage boundary: terms ($(reg_terms ? "registered" : "wire")) ----------------")
    emit_boundary(io, reg_terms, bound1)
    println(io)

    # ---------------- reduction ----------------
    tnames = ["terms_q[$(Ws*i) +: $(Ws)]" for i in 0:K-1]
    int_path || push!(tnames, "negfix_q")
    println(io, "  // ---------------- reduction: $(length(tnames)) operands → 1 ($(c.tree == :csa ? "3:2 CSA tree + CPA" : "adder tree")) ----------------")
    root = emit_tree(io, tnames, Ws, c.tree)
    println(io)
    bound2 = Tuple{String,String,String}[("logic [$(Ws-1):0]", "sum_q", root)]
    fpout && append!(bound2, [("logic", "nan_q", "nan_q1"), ("logic", "pinf_q", "pinf_q1"),
                              ("logic", "ninf_q", "ninf_q1"), ("logic signed [15:0]", "e_lsb_q", "e_lsb_q1")])
    println(io, "  // ---------------- stage boundary: sum ($(reg_sum ? "registered" : "wire")) ----------------")
    emit_boundary(io, reg_sum, bound2)
    println(io)

    # ---------------- output ----------------
    println(io, "  logic [$(WO-1):0] result_d;")
    if fpout
        emit_normalize_round(io, c, w)
    else
        OB = c.out.bits
        if OB >= Ws
            println(io, "  assign result_d = $(OB == Ws ? "sum_q" : "{{$(OB - Ws){sum_q[$(Ws-1)]}}, sum_q}");")
        else
            println(io, "  // saturate the $(Ws)-bit exact sum to $(OB) bits")
            println(io, "  logic fits;")
            println(io, "  assign fits = (sum_q[$(Ws-1):$(OB-1)] == '0) || (sum_q[$(Ws-1):$(OB-1)] == '1);")
            println(io, "  assign result_d = fits ? sum_q[$(OB-1):0] : (sum_q[$(Ws-1)] ? $(hexlit(OB, big(1) << (OB-1))) : $(hexlit(OB, (big(1) << (OB-1)) - 1)));")
        end
    end
    println(io)
    println(io, "  // ---------------- stage boundary: output ($(reg_out ? "registered" : "wire")) ----------------")
    if reg_out
        println(io, "  always_ff @(posedge clk_i or negedge rst_ni) begin")
        println(io, "    if (!rst_ni) result_o <= '0;")
        println(io, "    else         result_o <= result_d;")
        println(io, "  end")
    else
        println(io, "  assign result_o = result_d;")
    end
    if c.stages == 0
        println(io, "  assign valid_o = valid_i;")
    else
        S = c.stages
        println(io, "  logic [$(S-1):0] valid_sr;")
        println(io, "  always_ff @(posedge clk_i or negedge rst_ni) begin")
        println(io, "    if (!rst_ni) valid_sr <= '0;")
        println(io, "    else         valid_sr <= $(S == 1 ? "valid_i" : "{valid_sr[$(S-2):0], valid_i}");")
        println(io, "  end")
        println(io, "  assign valid_o = valid_sr[$(S-1)];")
    end
    println(io)
    println(io, "endmodule")
    return String(take!(io))
end

# Single normalization + rounding of `sum_q * 2^e_lsb_q` to the float output format.
function emit_normalize_round(io, c::DotConfig, w)
    o = c.out::FPOut
    EB, MB = o.ebits, o.mbits
    Ws, Wn = w.Ws, w.Wn
    PAD = Wn - Ws
    LZW = bitlen(Ws)
    DW = bitlen(Wn)
    B = bias(o)
    emaxf = (1 << EB) - 1
    WO = 1 + EB + MB
    nan = hexlit(WO, canonical_nan(o))
    pinf, ninf = hexlit(WO, inf_code(o, false)), hexlit(WO, inf_code(o, true))
    ovf_mag = c.rounding == :rne ? "{$(EB)'h$(string(emaxf, base=16)), $(MB)'h0}" :
              "{$(EB)'h$(string(emaxf - 1, base=16)), {$(MB){1'b1}}}"
    println(io, "  // ---------------- normalize once, round once ($(c.rounding)) → $(o) ----------------")
    println(io, "  logic              sgn, is_zero, g, st, sticky_d, inc, ovf_pre, ovf;")
    println(io, "  logic [$(Ws-1):0]  mag;")
    println(io, "  logic [$(LZW-1):0]  lz;")
    println(io, "  logic [$(Wn-1):0]  norm, shd;")
    println(io, "  logic [$(DW-1):0]  dsh;")
    println(io, "  logic signed [15:0] e_msb, biased, dneed;")
    println(io, "  logic [$(MB):0]   M;")
    println(io, "  logic [$(EB+MB):0] pk, pk_r;")
    println(io, "  always_comb begin")
    println(io, "    sgn     = sum_q[$(Ws-1)];")
    println(io, "    mag     = sgn ? -sum_q : sum_q;")
    println(io, "    is_zero = (mag == '0);")
    println(io, "    lz      = $(LZW)'d$(Ws);                       // leading-zero count")
    println(io, "    for (int k = 0; k < $(Ws); k++) if (mag[k]) lz = $(LZW)'($(Ws - 1) - k);")
    println(io, "    norm    = $(PAD == 0 ? "mag" : "{mag, $(PAD)'b0}") << lz;   // MSB at bit $(Wn-1)")
    println(io, "    e_msb   = e_lsb_q + $(slit(Ws - 1)) - \$signed({$(16 - LZW)'b0, lz});")
    println(io, "    biased  = e_msb + $(slit(B));")
    println(io, "    // subnormal result: shift right so the quantum is the format's minimum")
    println(io, "    dneed   = 16'sd1 - biased;")
    println(io, "    dsh     = (biased >= 16'sd1) ? '0 : (dneed >= $(slit(Wn))) ? $(DW)'d$(Wn) : dneed[$(DW-1):0];")
    println(io, "    shd     = norm >> dsh;")
    println(io, "    sticky_d = |(norm & ~({$(Wn){1'b1}} << dsh));")
    println(io, "    M       = shd[$(Wn-1):$(Wn-1-MB)];")
    println(io, "    g       = shd[$(Wn-2-MB)];")
    println(io, "    st      = (|shd[$(Wn-3-MB):0]) | sticky_d;")
    println(io, "    ovf_pre = (biased >= $(slit(emaxf)));")
    println(io, "    pk      = {1'b0, (biased >= 16'sd1) ? biased[$(EB-1):0] : $(EB)'d0, M[$(MB-1):0]};")
    println(io, "    inc     = ", c.rounding == :rne ? "g & (st | M[0]);   // ties to even" : "1'b0;   // toward zero", "")
    println(io, "    pk_r    = pk + {$(EB+MB)'b0, inc};             // carries into the exponent (incl. subnormal → normal)")
    println(io, "    ovf     = ovf_pre | (pk_r[$(EB+MB-1):$(MB)] == '1);")
    println(io, "    if      (nan_q)   result_d = $nan;")
    println(io, "    else if (pinf_q)  result_d = $pinf;")
    println(io, "    else if (ninf_q)  result_d = $ninf;")
    println(io, "    else if (is_zero) result_d = '0;")
    println(io, "    else if (ovf)     result_d = {sgn, $ovf_mag};")
    println(io, "    else              result_d = {sgn, pk_r[$(EB+MB-1):0]};")
    println(io, "  end")
end

"""
    emit_dot(cfg, dir) -> path

Write `<dir>/<cfg.name>.sv` and return its path.
"""
function emit_dot(c::DotConfig, dir::AbstractString)
    mkpath(dir)
    path = joinpath(dir, c.name * ".sv")
    write(path, emit_dot_string(c))
    return path
end
